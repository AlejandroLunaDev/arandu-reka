// Generates src/design-system/tokens.css from src/design-system/tokens.json, the design system's
// tokens copied as they are from https://claude.ai/artifact/NBNz4q9R1e4jJf9m1cLZaM.
//
//   node scripts/tokens.mjs           writes tokens.css
//   node scripts/tokens.mjs --check   fails when tokens.css is out of date
//
// The CSS keeps the design system's variable names (--bg, --text, --primary...), dark by default
// and light under [data-theme="light"]. It also writes the Tailwind theme: Tailwind's default
// colors, fonts, type scale, spacing, radii and shadows are switched off, so only token utilities
// exist (bg-surface, text-muted, p-3, rounded-card, type-h1...).

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const SOURCE = fileURLToPath(new URL("../src/design-system/tokens.json", import.meta.url));
const TARGET = fileURLToPath(new URL("../src/design-system/tokens.css", import.meta.url));

// next/font puts each face in its own variable: layout.tsx loads Outfit as --font-outfit.
const fontVariable = (face) => `--font-${face.toLowerCase().replace(/\s+/g, "-")}`;

// Type styles grow on wider screens, written in their usage as "36/42 on screens 768px and wider".
const WIDER = /(\d+)\/(\d+) on screens (\d+)px and wider/;

export function generate(tokens) {
  const colors = tokens.color.tokens;
  const dark = (t) => (typeof t.value === "string" ? t.value : t.value.dark);
  const families = Object.entries(tokens.type.families).map(([name, stack]) => {
    const [face, ...fallbacks] = stack.split(",").map((s) => s.trim());
    return [name, [`var(${fontVariable(face)}, ${face})`, ...fallbacks].join(", ")];
  });
  const styles = tokens.type.groups.flatMap((group) => group.styles.map((style) => ({ ...style, family: group.family })));

  return [
    "/* Generated by scripts/tokens.mjs from tokens.json. Do not edit: run npm run tokens. */",
    "",
    ':root, [data-theme="dark"] {',
    ...colors.map((t) => `  --${t.name}: ${dark(t).toLowerCase()};`),
    "}",
    "",
    '[data-theme="light"] {',
    ...colors.filter((t) => typeof t.value !== "string").map((t) => `  --${t.name}: ${t.value.light.toLowerCase()};`),
    "}",
    "",
    "@theme {",
    "  --color-*: initial;",
    "  --font-*: initial;",
    "  --text-*: initial;",
    "  --font-weight-*: initial;",
    "  --tracking-*: initial;",
    "  --leading-*: initial;",
    "  --spacing: initial;",
    "  --spacing-*: initial;",
    "  --radius-*: initial;",
    "  --shadow-*: initial;",
    "  --inset-shadow-*: initial;",
    "  --drop-shadow-*: initial;",
    "  --text-shadow-*: initial;",
    "",
    ...families.map(([name, stack]) => `  --font-${name}: ${stack};`),
    "  --spacing-0: 0px; /* not a design value: keeps p-0, gap-0 and inset-0 */",
    ...tokens.spacing.tokens.map((t) => `  --spacing-${t.name.replace(/^space-/, "")}: ${t.value};`),
    ...tokens.radius.tokens.map((t) => `  --${t.name}: ${t.value};`),
    "}",
    "",
    "@theme inline {",
    ...colors.map((t) => `  --color-${t.name}: var(--${t.name});`),
    "}",
    ...styles.flatMap((style) => {
      const wider = style.usage.match(WIDER);
      return [
        "",
        `@utility type-${style.name} {`,
        `  font-family: var(--font-${style.family});`,
        `  font-size: ${style.fontSize};`,
        `  line-height: ${style.lineHeight};`,
        `  font-weight: ${style.fontWeight};`,
        ...(style.letterSpacing ? [`  letter-spacing: ${style.letterSpacing};`] : []),
        ...(wider
          ? [`  @media (width >= ${wider[3]}px) {`, `    font-size: ${wider[1]}px;`, `    line-height: ${wider[2]}px;`, "  }"]
          : []),
        "}",
      ];
    }),
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const css = generate(JSON.parse(readFileSync(SOURCE, "utf8")));
  if (process.argv.includes("--check")) {
    if (readFileSync(TARGET, "utf8") !== css) {
      console.error("tokens.css is out of date: run npm run tokens.");
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, css);
  }
}
